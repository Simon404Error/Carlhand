# Generate shader_blob.h from fxc .cso files (ASCII only)
param(
    [Parameter(Mandatory=$true)][string]$Vs,
    [Parameter(Mandatory=$true)][string]$Ps,
    [Parameter(Mandatory=$true)][string]$Out
)

function Convert-Blob([string]$path, [string]$name, [System.Text.StringBuilder]$sb) {
    $b = [System.IO.File]::ReadAllBytes($path)
    [void]$sb.AppendLine("static const unsigned char $name[] = {")
    $line = "    "
    for ($i = 0; $i -lt $b.Length; $i++) {
        $line += ("0x{0:X2}," -f $b[$i])
        if ((($i + 1) % 16) -eq 0) { [void]$sb.AppendLine($line); $line = "    " }
    }
    if ($line.Trim().Length -gt 0) { [void]$sb.AppendLine($line) }
    [void]$sb.AppendLine("};")
    [void]$sb.AppendLine("")
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// auto generated by build/gen_blob.ps1 - do not edit")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("")
Convert-Blob $Vs "g_VS" $sb
Convert-Blob $Ps "g_PS" $sb
[System.IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "generated $Out"
